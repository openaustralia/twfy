{{-- The tips for searching, shown on the search page and in its sidebar. --}}
<x-prose>
<ul>
    <li>OpenAustralia.org Search is case-insensitive, and tries to match all the search terms within a document. </li>

    <li>To exclude a word from your search, put a minus ("-") sign in front,
        for example to find documents containing the word "representation" but not the word "taxation":<br>
        <code>representation -taxation</code>
    </li>

    <li>To search for an exact phrase, use quotes (""). For example to find only documents contain the exact phrase
        "Cole Inquiry":<br>
        <code>"Cole Inquiry"</code>
    </li>

    <li>If the search phrase matches (part of) a Representative's or Senator's name, their own page will appear as the
        top result.</li>

    <li>If your search term matches a glossary definition, a link to that definition will appear as the top result.</li>

    <li>From a Representative or Senator's page, you have the option to search only their speeches. </li>

</ul>
</x-prose>
