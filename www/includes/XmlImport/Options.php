<?php

namespace OpenAustralia\TWFY\XmlImport;

/**
 * The command-line options of scripts/importxml.php, which are the ones scripts/xml2db.pl takes.
 */
class Options {

    public bool $debates = false;

    public bool $senate = false;

    public bool $members = false;

    public bool $all = false;

    public ?string $date = null;

    public ?string $from = null;

    public ?string $to = null;

    public bool $force = false;

    public bool $quiet = false;

    public bool $cronquiet = false;

    /**
     * The options by name, and whether each takes a value. "lordsdebates" is the old name of "senatedebates".
     */
    private const NAMES = [
        'all' => false,
        'date' => true,
        'from' => true,
        'to' => true,
        'debates' => false,
        'senatedebates' => false,
        'lordsdebates' => false,
        'members' => false,
        'force' => false,
        'quiet' => false,
        'cronquiet' => false,
    ];

    /**
     * Parses the arguments after the script name, returning NULL when they are not valid.
     *
     * Like Getopt::Long, an unambiguous prefix of an option name is accepted.
     *
     * @param list<string> $arguments
     *   The arguments.
     * @param callable(string): void $complain
     *   Told about each argument that cannot be used.
     */
    public static function parse(array $arguments, callable $complain): ?self {
        $options = new self();
        $valid = true;
        for ($i = 0; $i < count($arguments); $i++) {
            if (!preg_match('/^--?([^=]+)(?:=(.*))?$/s', $arguments[$i], $match)) {
                $complain('Unknown argument: ' . $arguments[$i]);
                $valid = false;
                continue;
            }
            $name = self::resolve($match[1]);
            if ($name === null) {
                $complain('Unknown option: ' . $match[1]);
                $valid = false;
                continue;
            }
            $value = true;
            if (self::NAMES[$name]) {
                $value = $match[2] ?? ($arguments[++$i] ?? null);
                if ($value === null) {
                    $complain("Option $name requires an argument");
                    $valid = false;
                    continue;
                }
            }
            $options->set($name, $value);
        }
        if (!$valid) {
            return null;
        }
        $selectors = (int) $options->all + (int) ($options->date !== null) + (int) ($options->from !== null || $options->to !== null);
        if ($selectors !== 1 || !($options->debates || $options->senate || $options->members)) {
            return null;
        }
        return $options;
    }

    /**
     * The full option name for a name or unambiguous prefix, or NULL.
     */
    private static function resolve(string $name): ?string {
        if (isset(self::NAMES[$name])) {
            return $name;
        }
        $matches = array_filter(array_keys(self::NAMES), static fn (string $candidate): bool => str_starts_with($candidate, $name));
        return count($matches) === 1 ? reset($matches) : null;
    }

    /**
     * Stores one option.
     */
    private function set(string $name, string|bool $value): void {
        match ($name) {
            'all' => $this->all = true,
            'date' => $this->date = $value,
            'from' => $this->from = $value,
            'to' => $this->to = $value,
            'debates' => $this->debates = true,
            'senatedebates', 'lordsdebates' => $this->senate = true,
            'members' => $this->members = true,
            'force' => $this->force = true,
            'quiet' => $this->quiet = true,
            'cronquiet' => $this->cronquiet = true,
        };
    }

    /**
     * The first and last date to load: the --date day, the --from and --to range, or none.
     *
     * @return array{0: string, 1: string}
     *   Inclusive bounds, compared as strings.
     */
    public function dateRange(): array {
        if ($this->date !== null) {
            return [$this->date, $this->date];
        }
        if ($this->from !== null || $this->to !== null) {
            return [$this->from ?? '1000-01-01', $this->to ?? '9999-12-31'];
        }
        return ['9999-12-31', '1000-01-01'];
    }

    /**
     * The text printed when the options are not valid.
     */
    public static function usage(): string {
        return <<<'END'

Loads Australian parliamentary data into the TWFY database. This is the PHP
version of xml2db.pl, and takes the same options.

It reads XML files from the parldata (pwdata) directory. The files contain
debates and members, and were generated by openaustralia-parser. This script
synchronises the database to the files, so existing entries with the same gid
are updated preserving their database id.

--debates - process House of Representatives debates
--senatedebates or --lordsdebates - process Senate debates (both do the same)
--members - process members

--all - reprocess every single date back in time
--date=YYYY-MM-DD - reprocess just this date
--from=YYYY-MM-DD --to=YYYY-MM-DD - reprocess this date range

--force - also delete items from database that weren't in the XML
          file (applied per day only)
--quiet - don't print the contents whenever an existing entry is
          modified or deleted
--cronquiet - stop printing date names as entries are processed

END;
    }

}
